#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lists_do_not_overlap() {
        for f in PURE {
            assert!(!SIDE_EFFECT_WRITE.contains(f), "{f}");
            assert!(!SIDE_EFFECT_ADMIN.contains(f), "{f}");
        }
        for f in SIDE_EFFECT_WRITE {
            assert!(!SIDE_EFFECT_ADMIN.contains(f), "{f}");
        }
    }

    #[test]
    fn effects() {
        assert_eq!(effect("nextval"), Some(StatementClass::Write));
        assert_eq!(effect("pg_terminate_backend"), Some(StatementClass::Admin));
        assert_eq!(effect("system$cancel_query"), Some(StatementClass::Admin));
        assert_eq!(effect("count"), Some(StatementClass::Read));
        assert_eq!(effect("my_function"), None);
    }
}
