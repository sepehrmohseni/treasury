//! Functions that can appear in a SELECT and what they do.
//!
//! A SELECT is only a read if every function it calls is. Functions known to change data or
//! server state make it a write or an admin statement; in dialects where user-defined functions
//! can write, a function on neither list makes it unknown.

use treasury_core::analyze::StatementClass;

/// What calling `name` (lowercase, unqualified) does, or `None` when it is not known.
pub fn effect(name: &str) -> Option<StatementClass> {
    if SIDE_EFFECT_WRITE.contains(&name) {
        return Some(StatementClass::Write);
    }
    if SIDE_EFFECT_ADMIN.contains(&name) || name.starts_with("system$") {
        return Some(StatementClass::Admin);
    }
    if PURE.contains(&name) {
        return Some(StatementClass::Read);
    }
    None
}

